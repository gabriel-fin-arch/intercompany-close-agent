"""The evidence pack: what one finalized close leaves for a controls reviewer.

One folder per run, in CSV, JSON and plain text, so it opens without this
project installed:

  run.json          who prepared it and who reviewed it, when it was written,
                    the policy, the code version, and the SHA-256 of each
                    input file
  audit_trail.txt   the run's audit trail, one line per entry
  tieout.csv        each entity's IC subledger against its trial balance
  exceptions.csv    what matching found, how triage classified it and why,
                    the reviewer's decision, and whether anything was booked
  decisions.csv     every reviewer decision: what, who, when, amount, note
  eliminations.csv  every journal line the close booked

Everything in it is read from the run's own state; nothing is recomputed,
so the pack can't disagree with what the close did. `docs/controls.md` says
which of these files is the evidence for which control.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import os
import subprocess
import zipfile
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

PACK_FILES = (
    "run.json",
    "audit_trail.txt",
    "tieout.csv",
    "exceptions.csv",
    "decisions.csv",
    "eliminations.csv",
)
INPUT_FILES = ("entities.csv", "trial_balance.csv", "ic_ledger.csv")

NOTE = (
    "Produced by intercompany-close-agent. The project's sample data (data/synthetic) is "
    "synthetic, generated by the project itself; this run's inputs are identified by path "
    "and SHA-256 below. Names are as typed into the tool, not authenticated."
)


def code_version() -> str:
    """The commit the code ran from, as exactly as can be told.

    CI sets GITHUB_SHA. A local checkout asks git, and says so when the
    working tree has uncommitted changes, since then the commit alone doesn't
    describe the code that ran.
    """
    sha = os.environ.get("GITHUB_SHA")
    if sha:
        return sha
    try:
        head = _git("rev-parse", "HEAD")
        dirty = _git("status", "--porcelain", "--untracked-files=no")
    except (OSError, subprocess.CalledProcessError):
        return "unknown: not run from a git checkout"
    return f"{head} with uncommitted changes" if dirty else head


def _git(*args: str) -> str:
    completed = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True)
    return completed.stdout.strip()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _csv(header: list[str], rows: list[list[object]]) -> str:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(header)
    writer.writerows(rows)
    return out.getvalue()


def pack_files(state: dict, data_dir: Path, *, generated_at: datetime | None = None) -> dict[str, str]:
    """The pack's files, name to content, for a finalized run's state."""
    if "eliminations" not in state:
        raise ValueError("the run hasn't finalized; a close has no evidence pack until it has")

    generated_at = generated_at or datetime.now(UTC)
    policy = state["policy"]
    decisions = state.get("review_decisions", [])
    eliminations = state["eliminations"]
    triage_by_reference = {t.reference: t for t in state.get("triage_results", [])}
    decision_by_reference = {d.reference: d for d in decisions}
    booked = {e.reference for e in eliminations}

    run = {
        "note": NOTE,
        "generated_at": generated_at.isoformat(timespec="seconds").replace("+00:00", "Z"),
        "prepared_by": state["prepared_by"],
        "reviewers": sorted({d.reviewer for d in decisions}),
        "policy": {
            "source": policy.source,
            "materiality_threshold": str(policy.materiality_threshold),
            "amount_tolerance_floor": str(policy.amount_tolerance_floor),
            "amount_tolerance_rate": str(policy.amount_tolerance_rate),
            "tieout_tolerance": str(policy.tieout_tolerance),
        },
        "code_version": code_version(),
        "inputs": [
            {"file": str(data_dir / name), "sha256": _sha256(data_dir / name)} for name in INPUT_FILES
        ],
        "counts": {
            "ic_transaction_legs": len(state.get("ic_transactions", [])),
            "entities_not_tying_out": sum(not v.within_tolerance for v in state.get("tb_variances", [])),
            "clean_pairs": len(state.get("clean_pairs", [])),
            "exceptions": len(state.get("exceptions", [])),
            "decisions": len(decisions),
            "eliminations": len(eliminations),
        },
    }

    tieout = _csv(
        ["entity_code", "ledger_total", "trial_balance_total", "variance", "within_tolerance"],
        [
            [v.entity_code, v.ledger_total, v.trial_balance_total, v.variance, v.within_tolerance]
            for v in state.get("tb_variances", [])
        ],
    )

    exception_rows: list[list[object]] = []
    for exc in state.get("exceptions", []):
        triage = triage_by_reference.get(exc.reference)
        decision = decision_by_reference.get(exc.reference)
        exception_rows.append(
            [
                exc.reference,
                exc.exception_type.value,
                exc.materiality.value,
                "" if exc.net_amount is None else exc.net_amount,
                exc.detected_reason,
                triage.classification.value if triage else "",
                f"{triage.confidence:.2f}" if triage else "",
                triage.rationale if triage else "",
                decision.action.value if decision else "",
                decision.reviewer if decision else "",
                "yes" if exc.reference in booked else "no",
            ]
        )
    exceptions = _csv(
        [
            "reference",
            "exception_type",
            "materiality",
            "net_amount",
            "detected_reason",
            "triage_classification",
            "triage_confidence",
            "triage_rationale",
            "decision",
            "reviewer",
            "booked",
        ],
        exception_rows,
    )

    decisions_csv = _csv(
        ["reference", "action", "reviewer", "decided_at", "override_amount", "reviewer_note"],
        [
            [
                d.reference,
                d.action.value,
                d.reviewer,
                d.decided_at.isoformat(timespec="seconds").replace("+00:00", "Z"),
                "" if d.override_amount is None else d.override_amount,
                d.reviewer_note,
            ]
            for d in decisions
        ],
    )

    eliminations_csv = _csv(
        ["reference", "line", "line_type", "entity_code", "account_code", "amount", "narrative"],
        [
            [e.reference, n, line.line_type.value, line.entity_code, line.account_code, line.amount, e.narrative]
            for e in eliminations
            for n, line in enumerate(e.lines, start=1)
        ],
    )

    return {
        "run.json": json.dumps(run, indent=2, ensure_ascii=False) + "\n",
        "audit_trail.txt": "".join(f"{line}\n" for line in state["audit_trail"]),
        "tieout.csv": tieout,
        "exceptions.csv": exceptions,
        "decisions.csv": decisions_csv,
        "eliminations.csv": eliminations_csv,
    }


def pack_name(generated_at: datetime) -> str:
    return f"close-{generated_at:%Y%m%dT%H%M%SZ}"


def write_pack(state: dict, out_root: Path, data_dir: Path) -> Path:
    """Write a finalized run's pack into a new folder under out_root.

    The folder is named for the time it was written. A second pack in the
    same second gets a suffix rather than overwriting the first.
    """
    generated_at = datetime.now(UTC)
    files = pack_files(state, data_dir, generated_at=generated_at)
    out_root.mkdir(parents=True, exist_ok=True)
    folder = out_root / pack_name(generated_at)
    suffix = 1
    while folder.exists():
        suffix += 1
        folder = out_root / f"{pack_name(generated_at)}-{suffix}"
    folder.mkdir()
    for name, content in files.items():
        (folder / name).write_bytes(content.encode("utf-8"))
    return folder


def zip_pack(folder: Path) -> bytes:
    """The pack in a written folder as one zip, for a download button."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in PACK_FILES:
            archive.write(folder / name, arcname=f"{folder.name}/{name}")
    return buffer.getvalue()
